"""
Train AlphaQubit model from .npz files generated by generate_realistic_noise_data.py

This script bridges the gap between our realistic noise data generator
(which outputs .npz files) and the model training code.

Usage:
    python train_from_npz.py --data-dir pretrain_data/realistic --epochs 20 --npu
"""

